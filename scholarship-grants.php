function isg_parse_requirement_lines(string $requirementsText): array
{
  $items = [];
  foreach (preg_split('/\r\n|\r|\n/', $requirementsText) as $line) {
    $line = trim((string)$line);
    if ($line === "") {
      continue;
    }
    $key = strtolower($line);
    if (!isset($items[$key])) {
      $items[$key] = $line;
    }
  }

  return array_values($items);
}

function isg_ensure_scholarship_grants_column(mysqli $conn, string $columnName, string $definition): bool
{
  $columnName = trim($columnName);
  if ($columnName === "") {
    return false;
  }

  $safeColumnName = $conn->real_escape_string($columnName);
  $columnResult = $conn->query("SHOW COLUMNS FROM scholarship_grants LIKE '{$safeColumnName}'");
  $hasColumn = $columnResult instanceof mysqli_result && $columnResult->num_rows > 0;
  if ($columnResult instanceof mysqli_result) {
    $columnResult->free();
  }
  if ($hasColumn) {
    return true;
  }

  return $conn->query("ALTER TABLE scholarship_grants ADD COLUMN {$columnName} {$definition}") === true;
}

function isg_backfill_default_scholarship_grant_details(mysqli $conn): void
{
  $stmt = $conn->prepare("
    UPDATE scholarship_grants
    SET
      qualification_text = CASE
        WHEN TRIM(COALESCE(qualification_text, '')) = '' THEN ?
        ELSE qualification_text
      END,
      program_text = CASE
        WHEN TRIM(COALESCE(program_text, '')) = '' THEN ?
        ELSE program_text
      END,
      benefits_text = CASE
        WHEN TRIM(COALESCE(benefits_text, '')) = '' THEN ?
        ELSE benefits_text
      END
    WHERE grant_id = ?
    LIMIT 1
  ");
  if (!$stmt) {
    return;
  }

  foreach (isg_default_scholarship_grants() as $grantId => $grant) {
    $qualificationText = (string)($grant["qualification_text"] ?? "");
    $programText = (string)($grant["program_text"] ?? "");
    $benefitsText = (string)($grant["benefits_text"] ?? "");
    $stmt->bind_param("sssi", $qualificationText, $programText, $benefitsText, $grantId);
    $stmt->execute();
  }

  $stmt->close();
}

function isg_ensure_scholarship_grants_tables(mysqli $conn): bool
{
  $grantSql = "
    CREATE TABLE IF NOT EXISTS scholarship_grants (
      grant_id INT NOT NULL PRIMARY KEY,
      title VARCHAR(255) NOT NULL,
      category_label VARCHAR(100) NOT NULL DEFAULT 'Scholarship Category',
      badge_label VARCHAR(100) NOT NULL DEFAULT 'Open for Application',
      description TEXT NULL,
      qualification_text TEXT NULL,
      program_text TEXT NULL,
      benefits_text TEXT NULL,
      is_active TINYINT(1) NOT NULL DEFAULT 1,
      sort_order INT NOT NULL DEFAULT 0,
      created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
      updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
    ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4
  ";
  if ($conn->query($grantSql) !== true) {
    return false;
  }
  if (
    !isg_ensure_scholarship_grants_column($conn, "qualification_text", "TEXT NULL AFTER description") ||
    !isg_ensure_scholarship_grants_column($conn, "program_text", "TEXT NULL AFTER qualification_text") ||
    !isg_ensure_scholarship_grants_column($conn, "benefits_text", "TEXT NULL AFTER program_text")
  ) {
    return false;
  }

  $requirementsSql = "
    CREATE TABLE IF NOT EXISTS scholarship_grant_requirements (
      id INT AUTO_INCREMENT PRIMARY KEY,
      grant_id INT NOT NULL,
      requirement_label VARCHAR(255) NOT NULL,
      sort_order INT NOT NULL DEFAULT 0,
      created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
      INDEX idx_scholarship_grant_requirements_grant (grant_id),
      CONSTRAINT fk_scholarship_grant_requirements_grant
        FOREIGN KEY (grant_id) REFERENCES scholarship_grants(grant_id)
        ON DELETE CASCADE
    ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4
  ";
  if ($conn->query($requirementsSql) !== true) {
    return false;
  }

  $countResult = $conn->query("SELECT COUNT(*) AS total FROM scholarship_grants");
  if (!$countResult instanceof mysqli_result) {
    return true;
  }

  $countRow = $countResult->fetch_assoc();
  $grantCount = (int)($countRow["total"] ?? 0);
  $countResult->free();
  if ($grantCount > 0) {
    isg_backfill_default_scholarship_grant_details($conn);
    return true;
  }

  $grantStmt = $conn->prepare("
    INSERT INTO scholarship_grants
      (grant_id, title, category_label, badge_label, description, qualification_text, program_text, benefits_text, is_active, sort_order)
    VALUES (?, ?, ?, ?, ?, ?, ?, ?, 1, ?)
  ");
  $requirementStmt = $conn->prepare("
    INSERT INTO scholarship_grant_requirements (grant_id, requirement_label, sort_order)
    VALUES (?, ?, ?)
  ");
  if (!$grantStmt || !$requirementStmt) {
    if ($grantStmt) {
      $grantStmt->close();
    }
    if ($requirementStmt) {
      $requirementStmt->close();
    }
    return false;
  }

  foreach (isg_default_scholarship_grants() as $grantId => $grant) {
    $title = (string)($grant["title"] ?? "");
    $categoryLabel = (string)($grant["category_label"] ?? "Scholarship Category");
    $badgeLabel = (string)($grant["badge_label"] ?? "Open for Application");
    $description = (string)($grant["description"] ?? "");
    $qualificationText = (string)($grant["qualification_text"] ?? "");
    $programText = (string)($grant["program_text"] ?? "");
    $benefitsText = (string)($grant["benefits_text"] ?? "");
    $sortOrder = (int)$grantId;
    $grantStmt->bind_param("isssssssi", $grantId, $title, $categoryLabel, $badgeLabel, $description, $qualificationText, $programText, $benefitsText, $sortOrder);
    $grantStmt->execute();

    foreach (($grant["requirements"] ?? []) as $requirementIndex => $requirementLabel) {
      $requirementLabel = trim((string)$requirementLabel);
      if ($requirementLabel === "") {
        continue;
      }
      $requirementSort = $requirementIndex + 1;
      $requirementStmt->bind_param("isi", $grantId, $requirementLabel, $requirementSort);
      $requirementStmt->execute();
    }
  }

  $grantStmt->close();
  $requirementStmt->close();
  return true;
}

function isg_load_scholarship_grants(mysqli $conn, bool $includeInactive = false): array
{
  if (!isg_ensure_scholarship_grants_tables($conn)) {
    return isg_default_scholarship_grants();
  }

  $grants = [];
  $where = $includeInactive ? "" : "WHERE is_active = 1";
  $result = $conn->query("
    SELECT grant_id, title, category_label, badge_label, description, qualification_text, program_text, benefits_text, is_active, sort_order
    FROM scholarship_grants
    {$where}
    ORDER BY sort_order ASC, grant_id ASC
  ");
  if ($result instanceof mysqli_result) {
    while ($row = $result->fetch_assoc()) {
      $grantId = (int)($row["grant_id"] ?? 0);
      if ($grantId <= 0) {
        continue;
      }
      $grants[$grantId] = [
        "grant_id" => $grantId,
        "title" => (string)($row["title"] ?? ""),
        "category_label" => (string)($row["category_label"] ?? "Scholarship Category"),
        "badge_label" => (string)($row["badge_label"] ?? "Open for Application"),
        "description" => (string)($row["description"] ?? ""),
        "qualification_text" => (string)($row["qualification_text"] ?? ""),
        "program_text" => (string)($row["program_text"] ?? ""),
        "benefits_text" => (string)($row["benefits_text"] ?? ""),
        "is_active" => (int)($row["is_active"] ?? 1),
        "sort_order" => (int)($row["sort_order"] ?? $grantId),
        "requirements" => [],
      ];
    }
    $result->free();
  }

  if (empty($grants)) {
    return [];
  }

  $activeClause = $includeInactive ? "" : "AND g.is_active = 1";
  $requirementResult = $conn->query("
    SELECT r.grant_id, r.requirement_label
    FROM scholarship_grant_requirements r
    INNER JOIN scholarship_grants g ON g.grant_id = r.grant_id
    WHERE 1 = 1 {$activeClause}
    ORDER BY r.grant_id ASC, r.sort_order ASC, r.id ASC
  ");
  if ($requirementResult instanceof mysqli_result) {
    while ($row = $requirementResult->fetch_assoc()) {
      $grantId = (int)($row["grant_id"] ?? 0);
      if (isset($grants[$grantId])) {
        $grants[$grantId]["requirements"][] = (string)($row["requirement_label"] ?? "");
      }
    }
    $requirementResult->free();
  }

  return $grants;
}

function isg_load_scholarship_grant_names(mysqli $conn, bool $includeInactive = false): array
{
  $names = [];
  foreach (isg_load_scholarship_grants($conn, $includeInactive) as $grantId => $grant) {
    $names[(int)$grantId] = (string)($grant["title"] ?? "");
  }

  return $names;
}

function isg_load_scholarship_grant_requirements(mysqli $conn, bool $includeInactive = false): array
{
  $requirements = [];
  foreach (isg_load_scholarship_grants($conn, $includeInactive) as $grantId => $grant) {
    $requirements[(int)$grantId] = $grant["requirements"] ?? [];
  }

  return $requirements;
}

function isg_get_scholarship_grant(mysqli $conn, int $grantId, bool $includeInactive = false): ?array
{
  if ($grantId <= 0) {
    return null;
  }

  $grants = isg_load_scholarship_grants($conn, $includeInactive);
  return $grants[$grantId] ?? null;
}

function isg_next_scholarship_grant_id(mysqli $conn): int
{
  if (!isg_ensure_scholarship_grants_tables($conn)) {
    return count(isg_default_scholarship_grants()) + 1;
  }

  $result = $conn->query("SELECT COALESCE(MAX(grant_id), 0) + 1 AS next_id FROM scholarship_grants");
  if (!$result instanceof mysqli_result) {
    return count(isg_default_scholarship_grants()) + 1;
  }

  $row = $result->fetch_assoc();
  $result->free();
  return max(1, (int)($row["next_id"] ?? 1));
}

function isg_insert_scholarship_grant_requirements(mysqli $conn, int $grantId, array $requirements): bool
{
  $stmt = $conn->prepare("
    INSERT INTO scholarship_grant_requirements (grant_id, requirement_label, sort_order)
    VALUES (?, ?, ?)
  ");
  if (!$stmt) {
    return false;
  }

  foreach (array_values($requirements) as $index => $requirementLabel) {
    $requirementLabel = trim((string)$requirementLabel);
    if ($requirementLabel === "") {
      continue;
    }
    $sortOrder = $index + 1;
    $stmt->bind_param("isi", $grantId, $requirementLabel, $sortOrder);
    if (!$stmt->execute()) {
      $stmt->close();
      return false;
    }
  }

  $stmt->close();
  return true;
}

function isg_add_scholarship_grant(mysqli $conn, string $title, string $categoryLabel, string $badgeLabel, string $description, string $qualificationText, string $programText, string $benefitsText, array $requirements, ?string &$error = null): bool
{
  $title = trim($title);
  $categoryLabel = trim($categoryLabel) !== "" ? trim($categoryLabel) : "Scholarship Category";
  $badgeLabel = trim($badgeLabel) !== "" ? trim($badgeLabel) : "Open for Application";
  $description = trim($description);
  $qualificationText = trim($qualificationText);
  $programText = trim($programText);
  $benefitsText = trim($benefitsText);

  if ($title === "") {
    $error = "Grant title is required.";
    return false;
  }
  if (!isg_ensure_scholarship_grants_tables($conn)) {
    $error = "Unable to prepare grant settings.";
    return false;
  }

  $grantId = isg_next_scholarship_grant_id($conn);
  $sortOrder = $grantId;
  $stmt = $conn->prepare("
    INSERT INTO scholarship_grants
      (grant_id, title, category_label, badge_label, description, qualification_text, program_text, benefits_text, is_active, sort_order)
    VALUES (?, ?, ?, ?, ?, ?, ?, ?, 1, ?)
  ");
  if (!$stmt) {
    $error = "Unable to save grant.";
    return false;
  }

  $stmt->bind_param("isssssssi", $grantId, $title, $categoryLabel, $badgeLabel, $description, $qualificationText, $programText, $benefitsText, $sortOrder);
  $ok = $stmt->execute();
  $stmt->close();
  if (!$ok) {
    $error = "Unable to save grant.";
    return false;
  }

  if (!isg_insert_scholarship_grant_requirements($conn, $grantId, $requirements)) {
    $error = "Grant was saved, but requirements could not be saved.";
    return false;
  }

  return true;
}

function isg_update_scholarship_grant(mysqli $conn, int $grantId, string $title, string $categoryLabel, string $badgeLabel, string $description, string $qualificationText, string $programText, string $benefitsText, array $requirements, ?string &$error = null): bool
{
  $title = trim($title);
  $categoryLabel = trim($categoryLabel) !== "" ? trim($categoryLabel) : "Scholarship Category";
  $badgeLabel = trim($badgeLabel) !== "" ? trim($badgeLabel) : "Open for Application";
  $description = trim($description);
  $qualificationText = trim($qualificationText);
  $programText = trim($programText);
  $benefitsText = trim($benefitsText);

  if ($grantId <= 0) {
    $error = "Invalid grant.";
    return false;
  }
  if ($title === "") {
    $error = "Grant title is required.";
    return false;
  }
  if (!isg_ensure_scholarship_grants_tables($conn)) {
    $error = "Unable to prepare grant settings.";
    return false;
  }

  $stmt = $conn->prepare("
    UPDATE scholarship_grants
    SET title = ?, category_label = ?, badge_label = ?, description = ?, qualification_text = ?, program_text = ?, benefits_text = ?, is_active = 1
    WHERE grant_id = ?
    LIMIT 1
  ");
  if (!$stmt) {
    $error = "Unable to update grant.";
    return false;
  }

  $stmt->bind_param("sssssssi", $title, $categoryLabel, $badgeLabel, $description, $qualificationText, $programText, $benefitsText, $grantId);
  $ok = $stmt->execute();
  $affectedRows = $stmt->affected_rows;
  $stmt->close();
  if (!$ok || $affectedRows < 0) {
    $error = "Unable to update grant.";
    return false;
  }

  $deleteStmt = $conn->prepare("DELETE FROM scholarship_grant_requirements WHERE grant_id = ?");
  if (!$deleteStmt) {
    $error = "Unable to update requirements.";
    return false;
  }
  $deleteStmt->bind_param("i", $grantId);
  $deleteOk = $deleteStmt->execute();
  $deleteStmt->close();
  if (!$deleteOk) {
    $error = "Unable to update requirements.";
    return false;
  }

  if (!isg_insert_scholarship_grant_requirements($conn, $grantId, $requirements)) {
    $error = "Unable to save requirements.";
    return false;
  }

  return true;
}

function isg_deactivate_scholarship_grant(mysqli $conn, int $grantId, ?string &$error = null): bool
{
  if ($grantId <= 0) {
    $error = "Invalid grant.";
    return false;
  }
  if (!isg_ensure_scholarship_grants_tables($conn)) {
    $error = "Unable to prepare grant settings.";
    return false;
  }

  $stmt = $conn->prepare("UPDATE scholarship_grants SET is_active = 0 WHERE grant_id = ? LIMIT 1");
  if (!$stmt) {
    $error = "Unable to remove grant.";
    return false;
  }

  $stmt->bind_param("i", $grantId);
  $ok = $stmt->execute();
  $stmt->close();
  if (!$ok) {
    $error = "Unable to remove grant.";
    return false;
  }

  return true;
}
